/**2. Tipo String
Declare uma variável com um texto e use métodos para:
Transformar todas as letras em maiúsculas.
Substituir uma palavra específica no texto por outra.
Exibir o comprimento da string. */

const texto = "Olá Dexter Morgan";
const apresentacao = "Olá nome, seja bem vindo ao site!";
const nomeUsuario = "Henrique";


// Transformando a frase em letras maiúsculas
console.log(texto.toUpperCase());

// Substituindo uma palavra específica no texto por outra
console.log(texto.replace("Dexter", "Luis"));

// Exibindo o comprimento da string
console.log(texto.length);

// Teste do replace para alterar alguma informação de boas vindas.
console.log(apresentacao.replace("nome", nomeUsuario));







