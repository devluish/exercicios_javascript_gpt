/**Tipo Boolean
Declare duas variáveis booleanas e use um console.log para verificar:
Se ambas são verdadeiras.
Se uma delas é falsa. */

const variavel1 = true;
const variavel2 = false;

// Verificar se ambas são verdadeiras.
console.log(variavel1 && variavel2);

// Verificar se uma delas é falsa
console.log(variavel1 || variavel2);



