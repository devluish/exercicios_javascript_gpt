/**Tipo Number
Crie duas variáveis com números decimais. Realize as seguintes operações:
Soma
Subtração
Multiplicação
Divisão com duas casas decimais. */

const numero1 = 52.5;
const numero2 = 570.4;


// Soma
console.log(numero1 + numero2);

// Subtração
console.log(numero1 - numero2);

// Multiplicação
console.log(numero1 * numero2);

// Divisão com duas casas decimais
const divisao = numero1 / numero2;
console.log(divisao.toFixed(2)); // Dica do GPT: Primeiro realizar a divisão e depois transformar as casa decimais desejadas.



